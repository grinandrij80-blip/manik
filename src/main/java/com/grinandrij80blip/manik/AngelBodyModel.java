package com.grinandrij80blip.manik;

import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.Identifier;
import net.minecraft.util.Mth;

/**
 * Hi-res (64 px per block) model generated by hires.py together with its texture.
 * Geometry is 4x the old size; ExtraBodyRenderer scales it back by 0.25.
 */
public final class AngelBodyModel extends EntityModel<ManiacBodyRenderState> {
    public static final ModelLayerLocation LAYER =
            new ModelLayerLocation(Identifier.parse("manik:angel_body"), "main");
    private static final float DEG = 0.017453292F;

    /** Converts an old-size y of a top-level part into this model's hi-res units. */
    private static float Y(float v) {
        return v * 4.0F - 72.048F;
    }

    private final ModelPart leg_r;
    private final ModelPart leg_l;
    private final ModelPart torso;
    private final ModelPart head;
    private final ModelPart jaw;
    private final ModelPart arm_r;
    private final ModelPart fore_r;
    private final ModelPart arm_l;
    private final ModelPart fore_l;
    private final ModelPart wing_r;
    private final ModelPart wing_l;

    public AngelBodyModel(ModelPart root) {
        super(root);
        this.leg_r = root.getChild("leg_r");
        this.leg_l = root.getChild("leg_l");
        this.torso = root.getChild("torso");
        this.head = this.torso.getChild("head");
        this.jaw = this.head.getChild("jaw");
        this.arm_r = this.torso.getChild("arm_r");
        this.fore_r = this.arm_r.getChild("fore_r");
        this.arm_l = this.torso.getChild("arm_l");
        this.fore_l = this.arm_l.getChild("fore_l");
        this.wing_r = this.torso.getChild("wing_r");
        this.wing_l = this.torso.getChild("wing_l");
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition p_leg_r = root.addOrReplaceChild("leg_r",
                CubeListBuilder.create()
                        .texOffs(96, 68).addBox(-6.0F, 0.0F, -6.0F, 12.0F, 32.0F, 12.0F),
                PartPose.offsetAndRotation(-6.0F, -8.048000000000002F, 0.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_leg_l = root.addOrReplaceChild("leg_l",
                CubeListBuilder.create()
                        .texOffs(144, 68).addBox(-6.0F, 0.0F, -6.0F, 12.0F, 32.0F, 12.0F),
                PartPose.offsetAndRotation(6.0F, -8.048000000000002F, 0.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_torso = root.addOrReplaceChild("torso",
                CubeListBuilder.create()
                        .texOffs(192, 68).addBox(-12.0F, -32.0F, -6.0F, 24.0F, 32.0F, 12.0F)
                        .texOffs(0, 68).addBox(-15.0F, -8.0F, -9.0F, 30.0F, 28.0F, 18.0F),
                PartPose.offsetAndRotation(0.0F, -8.048000000000002F, 0.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_head = p_torso.addOrReplaceChild("head",
                CubeListBuilder.create()
                        .texOffs(240, 0).addBox(-12.0F, -24.0F, -12.0F, 24.0F, 24.0F, 24.0F),
                PartPose.offsetAndRotation(0.0F, -32.0F, 0.0F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_jaw = p_head.addOrReplaceChild("jaw",
                CubeListBuilder.create()
                        .texOffs(32, 114).addBox(-8.0F, 0.0F, -2.0F, 16.0F, 10.0F, 12.0F),
                PartPose.offsetAndRotation(0.0F, -4.0F, -10.0F, 0.25F, 0.0F, 0.2F));
        PartDefinition p_arm_r = p_torso.addOrReplaceChild("arm_r",
                CubeListBuilder.create()
                        .texOffs(392, 68).addBox(-4.0F, 0.0F, -4.0F, 8.0F, 20.0F, 8.0F),
                PartPose.offsetAndRotation(-16.0F, -28.0F, 0.0F, 0.0F, 0.0F, 0.1F));
        PartDefinition p_fore_r = p_arm_r.addOrReplaceChild("fore_r",
                CubeListBuilder.create()
                        .texOffs(424, 68).addBox(-4.0F, 0.0F, -4.0F, 8.0F, 20.0F, 8.0F),
                PartPose.offsetAndRotation(0.0F, 20.0F, 0.0F, -0.3F, 0.0F, 0.0F));
        PartDefinition p_arm_l = p_torso.addOrReplaceChild("arm_l",
                CubeListBuilder.create()
                        .texOffs(456, 68).addBox(-4.0F, 0.0F, -4.0F, 8.0F, 20.0F, 8.0F),
                PartPose.offsetAndRotation(16.0F, -28.0F, 0.0F, 0.0F, 0.0F, -0.1F));
        PartDefinition p_fore_l = p_arm_l.addOrReplaceChild("fore_l",
                CubeListBuilder.create()
                        .texOffs(0, 114).addBox(-4.0F, 0.0F, -4.0F, 8.0F, 20.0F, 8.0F),
                PartPose.offsetAndRotation(0.0F, 20.0F, 0.0F, -0.3F, 0.0F, 0.0F));
        PartDefinition p_wing_r = p_torso.addOrReplaceChild("wing_r",
                CubeListBuilder.create()
                        .texOffs(0, 0).addBox(-56.0F, -60.0F, 0.0F, 56.0F, 64.0F, 4.0F)
                        .texOffs(336, 0).addBox(-40.0F, -28.0F, 4.0F, 40.0F, 44.0F, 4.0F)
                        .texOffs(264, 68).addBox(-28.0F, -8.0F, 8.0F, 28.0F, 28.0F, 4.0F),
                PartPose.offsetAndRotation(-6.0F, -24.0F, 7.2F, 0.0F, 0.0F, 0.0F));
        PartDefinition p_wing_l = p_torso.addOrReplaceChild("wing_l",
                CubeListBuilder.create()
                        .texOffs(120, 0).addBox(0.0F, -60.0F, 0.0F, 56.0F, 64.0F, 4.0F)
                        .texOffs(424, 0).addBox(0.0F, -28.0F, 4.0F, 40.0F, 44.0F, 4.0F)
                        .texOffs(328, 68).addBox(0.0F, -8.0F, 8.0F, 28.0F, 28.0F, 4.0F),
                PartPose.offsetAndRotation(6.0F, -24.0F, 7.2F, 0.0F, 0.0F, 0.0F));
        return LayerDefinition.create(mesh, 512, 512);
    }

    @Override
    public void setupAnim(ManiacBodyRenderState state) {
        super.setupAnim(state);
        float crouch = state.crouch;
        float speed = Math.min(1.0F, state.walkSpeed);
        float cycle = state.walkPos * 0.6F;
        float age = state.ageInTicks;
        float t = state.attack;
        float idle = 1.0F - Math.min(1.0F, speed * 4.0F);

        this.torso.y = Y(16.0F + crouch * 2.0F + Math.abs(Mth.cos(cycle)) * speed * 0.5F);
        this.leg_r.y = Y(16.0F + crouch * 2.0F);
        this.leg_l.y = Y(16.0F + crouch * 2.0F);
        this.torso.xRot = 0.15F + crouch * 0.3F + ManiacAnim.lean(t, -0.15F, 0.3F);
        this.torso.yRot = t > 0.0F ? Mth.sin(Mth.sqrt(t) * (float) Math.PI * 2.0F) * 0.25F : 0.0F;

        // Twitchy, crooked head that follows the gaze.
        this.head.xRot = state.xRot * DEG * 0.7F - 0.15F + Mth.sin(age * 0.11F) * 0.05F * idle;
        this.head.yRot = Mth.clamp(state.yRot, -70.0F, 70.0F) * DEG - this.torso.yRot;
        this.head.zRot = 0.22F + Mth.sin(age * 0.07F) * 0.06F;
        this.jaw.xRot = 0.25F + Mth.sin(age * 0.2F) * 0.06F;

        float swingR = Mth.cos(cycle + (float) Math.PI) * 0.5F * speed;
        float swingL = Mth.cos(cycle) * 0.5F * speed;
        float draw = ManiacAnim.armAngle(t, -1.6F, -1.3F);
        this.arm_r.xRot = swingR + draw;
        this.arm_l.xRot = swingL + draw * 0.8F;
        this.arm_r.zRot = 0.1F;
        this.arm_l.zRot = -0.1F;
        this.fore_r.xRot = -0.3F - Math.abs(draw) * 0.2F;
        this.fore_l.xRot = -0.3F;
        this.leg_r.xRot = Mth.cos(cycle) * 0.8F * speed - crouch * 0.4F;
        this.leg_l.xRot = Mth.cos(cycle + (float) Math.PI) * 0.8F * speed + crouch * 0.4F;

        // Wings: folded and twitching normally, spread and flapping while flying.
        boolean flying = state.wings;
        float flap = flying ? Mth.sin(age * 0.9F) * 0.5F : Mth.sin(age * 0.08F) * 0.05F;
        float spread = flying ? 0.9F : 0.25F;
        this.wing_r.zRot = -spread - flap;
        this.wing_l.zRot = spread + flap;
        this.wing_r.yRot = flying ? 0.35F : 0.1F;
        this.wing_l.yRot = flying ? -0.35F : -0.1F;
    }
}
